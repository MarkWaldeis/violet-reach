"""Pack detail roughness into the unused blue channel of detail normal maps.

Input : web/explore/public/detail/<class>_normal.webp + <class>_rough.webp
Output: web/explore/public/detail/<class>_detail.webp (lossless RGB WebP)

The runtime only uses normal XY; blue was therefore unused. Keeping one packed RGB
texture halves triplanar texture reads and GPU texture memory without changing any
source texel in normal XY or roughness R.
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
DETAIL = ROOT / "web" / "explore" / "public" / "detail"
CFG = ROOT / "tools" / "textures" / "textures.json"


def lossless_rgb(path: Path) -> np.ndarray:
    return np.asarray(Image.open(path).convert("RGB"), dtype=np.uint8)


def main() -> int:
    cfg = json.loads(CFG.read_text(encoding="utf-8"))
    names = [t["name"] for t in cfg["textures"] if t.get("kind") == "detail"]
    manifest_path = DETAIL / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    total = 0
    for name in names:
        normal_path = DETAIL / f"{name}_normal.webp"
        rough_path = DETAIL / f"{name}_rough.webp"
        out_path = DETAIL / f"{name}_detail.webp"
        normal = lossless_rgb(normal_path)
        rough = lossless_rgb(rough_path)
        if normal.shape != rough.shape:
            raise ValueError(f"{name}: normal/rough shape mismatch {normal.shape} != {rough.shape}")
        packed = normal.copy()
        packed[:, :, 2] = rough[:, :, 0]
        Image.fromarray(packed, "RGB").save(out_path, "WEBP", lossless=True, quality=100, method=6)

        check = lossless_rgb(out_path)
        if not np.array_equal(check[:, :, :2], normal[:, :, :2]) or not np.array_equal(check[:, :, 2], rough[:, :, 0]):
            raise ValueError(f"{name}: packed WebP is not byte-exact")
        size = out_path.stat().st_size
        total += size
        entry = manifest.get("textures", {}).get(name)
        if entry is not None:
            entry["files"] = [out_path.name]
        print(f"OK {out_path.name}: {size / 1024:.1f} KiB, XY normal + B roughness byte-exact")

    manifest["doc"] = {
        "layout": "<klasse>_detail.webp, 1024, lossless RGB WebP",
        "packed": "linear, RG = normal XY*0.5+0.5, B = roughness grayscale; tangent-space OpenGL (+Y oben)",
        "source": "generated by tools/textures/pack_detail.py from <klasse>_normal.webp and <klasse>_rough.webp",
    }
    manifest_path.write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"packed detail textures: {total / 1e6:.2f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
